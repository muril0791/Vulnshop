export default function Icone({ nome, tamanho = 20, preenchido = false, className, style }) {
  const d = CAMINHOS[nome];
  if (!d) return null;
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={tamanho}
      height={tamanho}
      viewBox="0 0 24 24"
      fill={preenchido ? 'currentColor' : 'none'}
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={{ flexShrink: 0, ...style }}
      aria-hidden="true"
      focusable="false"
    >
      {d}
    </svg>
  );
}

// Uma estrela com preenchimento fracionario (0..1) — para notas tipo 4,5.
function Estrela({ fill = 1, tamanho = 15 }) {
  const gid = 'est-' + useId().replace(/:/g, '');
  const d = 'M12 2 15.09 8.26 22 9.27 17 14.14 18.18 21.02 12 17.77 5.82 21.02 7 14.14 2 9.27 8.91 8.26Z';
  return (
    <svg width={tamanho} height={tamanho} viewBox="0 0 24 24" aria-hidden="true" style={{ flexShrink: 0 }}>
      <defs>
        <linearGradient id={gid}>
          <stop offset={fill} stopColor="currentColor" />
          <stop offset={fill} stopColor="transparent" />
        </linearGradient>
      </defs>
      <path d={d} fill={`url(#${gid})`} stroke="currentColor" strokeWidth="1.5" strokeLinejoin="round" />
    </svg>
  );
}

// Linha de 5 estrelas a partir de um valor 0..5 (meia estrela suportada).
export function Estrelas({ valor = 0, tamanho = 15 }) {
  return (
    <span className="estrelas" role="img" aria-label={`${valor} de 5 estrelas`} style={{ display: 'inline-flex', gap: 1 }}>
      {[0, 1, 2, 3, 4].map((i) => (
        <Estrela key={i} tamanho={tamanho} fill={Math.max(0, Math.min(1, valor - i))} />
      ))}
    </span>
  );
}
